//! Generates `tlca.ziggy-schema` (TLCA collection files) from
//! `tla.ziggy-schema` (TLA timeline files).
//!
//! The ziggy schema language has no imports, so the collection schema is the
//! timeline schema with its root swapped to `Collection`, plus the types in
//! `tlca_collection.ziggy-schema.part`.
//!
//! Regenerate with `zig build update_tlca_schema`.  A test in
//! `serialization/ascii.zig` fails if the checked-in file is out of date.

const std = @import("std");

const TLA_ROOT = "$ = Timeline\n";
const TLCA_ROOT = "$ = Collection\n";

/// The generated TLCA schema.
pub const TLCA_SCHEMA: [:0]const u8 = generate(
    @embedFile("tla.ziggy-schema"),
    @embedFile("tlca_collection.ziggy-schema.part"),
);

/// Build the TLCA schema from the TLA schema and the collection types.
///
/// The notice is merged into the TLA schema's leading doc comment: the
/// schema parser only accepts doc comments before the first top-level
/// declaration.
fn generate(
    comptime tla_schema: []const u8,
    comptime collection_types: []const u8,
) [:0]const u8
{
    comptime {
        if (!std.mem.startsWith(u8, tla_schema, TLA_ROOT ++ "\n///"))
        {
            @compileError(
                "tla.ziggy-schema must start with '" ++ TLA_ROOT
                ++ "', a blank line, and a doc comment"
            );
        }

        const notice = (
            "/// GENERATED by `zig build update_tlca_schema` from\n"
            ++ "/// tla.ziggy-schema and tlca_collection.ziggy-schema.part;"
            ++ " do not edit.\n"
            ++ "///\n"
        );

        const out = (
            TLCA_ROOT ++ "\n" ++ notice
            ++ tla_schema[TLA_ROOT.len + 1 ..]
            ++ collection_types
            ++ "\x00"
        );
        return out[0 .. out.len - 1 :0];
    }
}

pub fn main(
    init: std.process.Init,
) !void
{
    var buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    try stdout.interface.writeAll(TLCA_SCHEMA);
    try stdout.interface.flush();
}
